/**
 * 要約後の自動タイトルに会議の開始日の接頭辞が付くことを検証する。
 * 対応する要求: REQ-SUMMARY-003
 */
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { DEFAULT_MEETING_TITLE } from '../src/shared/title';
import type { ChatCompletionRequest, LlmClient } from '../src/main/llm';
import { MeetingStore } from '../src/main/meetings';
import { generateAndSaveMeetingTitle } from '../src/main/meeting-title';

const MEETING_ID = '00000000-0000-4000-8000-0000000000f1';
const roots: string[] = [];

async function createMeeting() {
  const root = await mkdtemp(join(tmpdir(), 'kataribe-meeting-title-'));
  roots.push(root);
  const meetingDir = join(root, '2026', `2026-10-29_${DEFAULT_MEETING_TITLE}`);
  await mkdir(meetingDir, { recursive: true });
  await writeFile(
    join(meetingDir, 'meta.json'),
    JSON.stringify({
      schema_version: 1,
      id: MEETING_ID,
      status: 'summarized',
      title: DEFAULT_MEETING_TITLE,
      started_at: '2026-10-29T12:00:00',
      duration: 60,
      source: { input: 'both' },
      sample_rate: 48000,
      channels: 1,
      bits_per_sample: 16,
      chunks: [],
      expected_samples: 0,
      actual_samples: 0,
      audio_path: 'audio.mp3',
    }),
  );
  const store = new MeetingStore(root);
  const meeting = await store.find(MEETING_ID);
  if (!meeting) {
    throw new Error('meeting was not created');
  }
  return { root, store, meeting };
}

function createClient(title: string): LlmClient {
  return {
    complete: vi.fn(async (_request: ChatCompletionRequest) => ({
      text: title,
      inputTokens: 10,
      outputTokens: 5,
      status: 200,
    })),
  } as unknown as LlmClient;
}

afterEach(async () => {
  await Promise.all(
    roots.splice(0).map((root) => rm(root, { recursive: true, force: true })),
  );
});

describe('generateAndSaveMeetingTitle', () => {
  it('prefixes the meeting start date to the generated title', async () => {
    const { root, store, meeting } = await createMeeting();

    const updated = await generateAndSaveMeetingTitle({
      meetingStore: store,
      client: createClient('ASM診断結果の対応方針確認'),
      meeting,
      transcriptBody: '[00:00:01] テスト',
      language: 'ja',
      kind: 'openai',
      endpoint: 'https://example.com/v1/chat/completions',
      apiKey: 'key',
      model: 'model',
      provider: 'openai',
      now: () => new Date('2026-10-29T13:00:00'),
    });

    expect(updated.title).toBe('2026-10-29_ASM診断結果の対応方針確認');
    expect(updated.meetingDir).toBe(
      join(root, '2026', '2026-10-29_ASM診断結果の対応方針確認'),
    );
  });

  it('replaces a date generated by the LLM with the meeting date', async () => {
    const { root, store, meeting } = await createMeeting();

    const updated = await generateAndSaveMeetingTitle({
      meetingStore: store,
      client: createClient('2026-10-28_ASM診断結果の対応方針確認'),
      meeting,
      transcriptBody: '[00:00:01] テスト',
      language: 'ja',
      kind: 'openai',
      endpoint: 'https://example.com/v1/chat/completions',
      apiKey: 'key',
      model: 'model',
      provider: 'openai',
      now: () => new Date('2026-10-29T13:00:00'),
    });

    expect(updated.title).toBe('2026-10-29_ASM診断結果の対応方針確認');
    expect(updated.meetingDir).toBe(
      join(root, '2026', '2026-10-29_ASM診断結果の対応方針確認'),
    );
  });
});
